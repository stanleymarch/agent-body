/**
 * Regenerates src/fonts-charset.ts.
 *
 * UIKit's TTFLoader builds a single-channel MSDF atlas with a fixed default
 * charset (ASCII without `_`), so any other character is reported as a
 * missing glyph. The brand fonts need Latin, Cyrillic and typographic
 * punctuation, so the atlas charset is the intersection of the three bundled
 * fonts and the wanted ranges, written out as a string.
 *
 * Usage: node tools/font-charset.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = resolve(here, '../public/fonts');
const fonts = ['Unbounded-Bold.ttf', 'Geologica-Light.ttf', 'JetBrainsMono-Regular.ttf'];

function readCmap(file) {
  const buffer = readFileSync(resolve(fontsDir, file));
  const numTables = buffer.readUInt16BE(4);
  let cmapOffset = 0;
  for (let index = 0; index < numTables; index++) {
    const record = 12 + index * 16;
    if (buffer.toString('ascii', record, record + 4) === 'cmap') cmapOffset = buffer.readUInt32BE(record + 8);
  }
  if (!cmapOffset) throw new Error(`${file}: no cmap table`);
  const codes = new Set();
  const tableCount = buffer.readUInt16BE(cmapOffset + 2);
  for (let index = 0; index < tableCount; index++) {
    const record = cmapOffset + 4 + index * 8;
    const offset = cmapOffset + buffer.readUInt32BE(record + 4);
    const format = buffer.readUInt16BE(offset);
    if (format === 4) {
      const segCountX2 = buffer.readUInt16BE(offset + 6);
      const segCount = segCountX2 / 2;
      const endBase = offset + 14;
      const startBase = endBase + segCountX2 + 2;
      for (let segment = 0; segment < segCount; segment++) {
        const end = buffer.readUInt16BE(endBase + segment * 2);
        const start = buffer.readUInt16BE(startBase + segment * 2);
        if (start === 0xffff) continue;
        for (let code = start; code <= end; code++) codes.add(code);
      }
    } else if (format === 12) {
      const groups = buffer.readUInt32BE(offset + 12);
      for (let group = 0; group < groups; group++) {
        const entry = offset + 16 + group * 12;
        const start = buffer.readUInt32BE(entry);
        const end = buffer.readUInt32BE(entry + 4);
        for (let code = start; code <= end; code++) codes.add(code);
      }
    }
  }
  return codes;
}

const ranges = [
  [0x20, 0x7e],   // ASCII, including _ and every URL/ID character
  [0xa0, 0xff],   // Latin-1 supplement: « » · ° ± × ÷ №
  [0x400, 0x4ff], // Cyrillic
  [0x2010, 0x2027], // dashes, quotes, bullets, ellipsis
  [0x2030, 0x203a], // per mille, single guillemets
  [0x20ac, 0x20ac], // euro
  [0x20bd, 0x20bd], // rouble
  [0x2116, 0x2116], // numero
  [0x2122, 0x2122], // trademark
  [0x2190, 0x2193], // arrows
  [0x2212, 0x2212], // minus sign
  [0x25a0, 0x25cf], // geometric shapes
];

let allowed = null;
for (const font of fonts) {
  const cmap = readCmap(font);
  allowed = allowed === null
    ? new Set(cmap)
    : new Set([...allowed].filter((code) => cmap.has(code)));
}

const chars = [];
for (const [start, end] of ranges) {
  for (let code = start; code <= end; code++) {
    if (allowed.has(code)) chars.push(String.fromCodePoint(code));
  }
}
const charset = chars.join('');
const escaped = charset.replace(/\\/gu, '\\\\').replace(/'/gu, "\\'");

const output = `/**
 * Generated by tools/font-charset.mjs - do not edit by hand.
 *
 * Characters present in all three brand fonts: ASCII, Latin-1 supplement,
 * Cyrillic and the typographic punctuation used by the panel.
 */
export const BRAND_CHARSET = '${escaped}';
`;
writeFileSync(resolve(here, '../src/fonts-charset.ts'), output, 'utf8');
console.log(`charset: ${charset.length} characters written to src/fonts-charset.ts`);
